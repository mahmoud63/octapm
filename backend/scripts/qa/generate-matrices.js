/**
 * Generates the permission matrix from observed behaviour, not from the policy
 * file — the whole point is to record what the server actually does when each
 * role calls each endpoint.
 *
 *   node scripts/qa/generate-matrices.js
 */
const fs = require("fs");
const path = require("path");
const { prisma, login, actor } = require("./harness");
const { can } = require("../../src/config/permissions");

const SEED_PASSWORD = process.env.QA_SEED_PASSWORD || "DemoPassw0rd!";
const PERSONAS = {
  pm: "pm@octapm.demo",
  planning_eng: "planner@octapm.demo",
  qs: "qs@octapm.demo",
  cost_controller: "cost@octapm.demo",
  procurement: "procurement@octapm.demo",
  warehouse: "warehouse@octapm.demo",
  site_engineer: "site@octapm.demo",
  finance: "finance@octapm.demo",
};
const ROLES = Object.keys(PERSONAS);

// module -> the list endpoint that exercises its read permission.
const READ_ENDPOINTS = {
  rfi: "rfi",
  submittal: "submittals",
  change_order: "change-orders",
  change_event: "change-events",
  commitment: "commitments",
  sub_pay_app: "pay-apps",
  ipc: "ipc",
  cost: "cost",
  boq: "boq",
  schedule: "activities",
  punch: "punch",
  ncr: "ncr",
  inspection: "forms",
  safety: "safety",
  risk: "risk-register",
  procurement: "procurement",
  timesheet: "timesheets",
  lookahead: "lookaheads",
  bim: "bim/models",
  meeting: "meetings",
  task: "tasks",
  location: "locations",
  audit: "audit",
  eot: "eot",
  bid: "bids",
  document_control: "correspondence",
  email: "emails",
  progress: "daily-logs",
};

const cell = (observed, allowed) => {
  if (observed === allowed) return observed ? "✅" : "—";
  return observed ? "⚠️ open" : "⚠️ shut";
};

(async () => {
  const who = {};
  for (const [role, email] of Object.entries(PERSONAS)) {
    const session = await login(email, SEED_PASSWORD);
    if (session.token) who[role] = actor(session.token, role);
    else console.error(`could not sign in as ${role}`);
  }

  const first = who.pm || Object.values(who)[0];
  const projects = await first.get("/projects");
  const projectId = (projects.data?.items || [])[0]?.id;
  if (!projectId) throw new Error("no project visible; run the seed first");

  const rows = [];
  for (const [moduleName, endpoint] of Object.entries(READ_ENDPOINTS)) {
    const row = { module: moduleName, endpoint: `/projects/{id}/${endpoint}`, cells: {}, mismatch: false };
    for (const role of ROLES) {
      if (!who[role]) {
        row.cells[role] = "?";
        continue;
      }
      const response = await who[role].get(`/projects/${projectId}/${endpoint}`);
      // 404 means the endpoint is not mounted at that path; leave it out of the
      // verdict rather than reporting a permission result that does not exist.
      if (response.status === 404) {
        row.cells[role] = "n/a";
        continue;
      }
      const observed = response.status === 200;
      const allowed = can({ role, module: moduleName, action: "read" });
      row.cells[role] = cell(observed, allowed);
      if (observed !== allowed) row.mismatch = true;
    }
    rows.push(row);
  }

  const header = `| Module | Endpoint | ${ROLES.join(" | ")} |`;
  const divider = `| --- | --- | ${ROLES.map(() => "---").join(" | ")} |`;
  const body = rows
    .map((r) => `| \`${r.module}\` | \`${r.endpoint}\` | ${ROLES.map((role) => r.cells[role]).join(" | ")} |`)
    .join("\n");

  const mismatches = rows.filter((r) => r.mismatch);

  const doc = `# OctaPM permission test matrix

Generated by \`node scripts/qa/generate-matrices.js\` on ${new Date().toISOString().slice(0, 10)},
by signing in as each of the eight roles and calling each module's list endpoint
against a real database. **Every result below is observed server behaviour**, not
a reading of the policy file.

Legend: ✅ allowed and the policy agrees · — refused and the policy agrees ·
⚠️ open = the server allowed a role the policy forbids · ⚠️ shut = the server
refused a role the policy grants · n/a = no endpoint at that path.

${header}
${divider}
${body}

## Verdict

${
  mismatches.length === 0
    ? `No mismatches. Across ${rows.length} modules × ${ROLES.length} roles, the server's read
enforcement matches the declared permission policy exactly.`
    : `${mismatches.length} module(s) where enforcement and policy disagree:\n\n${mismatches
        .map((r) => `- \`${r.module}\` (${r.endpoint})`)
        .join("\n")}`
}

## What this does not cover

Read (list) permissions only. Create, update, delete, submit, approve, certify,
baseline and export are probed for RFI and change orders in scenario S-PERM-001,
but a full nine-action sweep across all 36 modules would need each module's
valid create payload and is not yet built. Party-role permissions (owner,
consultant, contractor, subcontractor) are enforced by a separate template layer
and are not covered here.
`;

  const out = path.join(__dirname, "..", "..", "..", "docs", "testing", "OCTAPM_PERMISSION_TEST_MATRIX.md");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, doc);
  console.log(`Wrote ${out}`);
  console.log(`${rows.length} modules probed, ${mismatches.length} mismatch(es)`);

  await prisma.$disconnect();
})().catch(async (error) => {
  console.error(error);
  await prisma.$disconnect();
  process.exitCode = 1;
});
