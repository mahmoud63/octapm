const daysBetween = (from, to) => (from && to ? Math.round((new Date(to).getTime() - new Date(from).getTime()) / DAY_MS) : null);
const isOverdue = (dueDate, closedStatuses, status) => Boolean(dueDate && new Date(dueDate) < today() && !closedStatuses.includes(String(status || "").toLowerCase()));
const daysOpen = (openedAt, closedAt) => (openedAt ? daysBetween(openedAt, closedAt || today()) : null);

