const ExcelJS = require("exceljs");
const { createPdf } = require("../pdf-writer");
const { brandWorkbook, addAboutSheet, ARGB } = require("../export-branding");

/**
 * Anything printed or exported from the portal has to be identifiable and has
 * to say where it came from. These pin the brand into the bytes, not just into
 * the code that writes them.
 */
describe("export branding", () => {
  const previousUrl = process.env.WEB_APP_URL;
  beforeAll(() => {
    process.env.WEB_APP_URL = "https://octapm.example.com";
  });
  afterAll(() => {
    if (previousUrl === undefined) delete process.env.WEB_APP_URL;
    else process.env.WEB_APP_URL = previousUrl;
  });

  describe("PDF", () => {
    const render = (options = {}) => {
      const pdf = createPdf({ title: "Punch list", footer: "Riverside Tower", ...options });
      pdf.heading("Section");
      pdf.paragraph("Body copy.");
      return pdf.render().toString("latin1");
    };

    it("puts the wordmark, signature and portal link on the page", () => {
      const bytes = render();
      expect(bytes).toContain("(octapm)");
      expect(bytes).toContain("Generated by OctaPM");
      expect(bytes).toContain("One Platform, Total Project Control");
      expect(bytes).toContain("https://octapm.example.com");
    });

    it("makes the footer link a real clickable annotation", () => {
      const bytes = render();
      expect(bytes).toContain("/Subtype /Link");
      expect(bytes).toContain("/URI (https://octapm.example.com)");
      expect(bytes).toContain("/Annots");
    });

    it("paints the Midnight Indigo header band with the octagonal motif", () => {
      const bytes = render();
      // The band: brand fill followed by a full-width rectangle.
      expect(bytes).toContain("0.059 0.106 0.392 rg");
      // The motif is stroked in Royal Blue; `h` closes each octagon path.
      expect(bytes).toContain("0.196 0.373 0.925 RG");
      expect(bytes).toMatch(/l \d+\.\d+ \d+\.\d+ l h S/);
    });

    it("keeps content clear of the header band and the footer", () => {
      const pdf = createPdf({ title: "Spacing" });
      // The writable area starts below the band, not at the page edge.
      expect(pdf.contentTop).toBeLessThan(pdf.pageHeight - pdf.margin);
      expect(pdf.contentBottom).toBeGreaterThan(pdf.margin);
      expect(pdf.y).toBe(pdf.contentTop);
    });

    it("can be turned off for a document that must be unbranded", () => {
      const bytes = render({ brand: false });
      expect(bytes).not.toContain("(octapm)");
      expect(bytes).not.toContain("/Subtype /Link");
    });
  });

  describe("workbooks", () => {
    const build = async () => {
      const workbook = new ExcelJS.Workbook();
      const sheet = workbook.addWorksheet("Data");
      sheet.columns = [
        { header: "Cost code", key: "code", width: 18 },
        { header: "Amount", key: "amount", width: 14 },
      ];
      sheet.addRow({ code: "01-CONC", amount: 500000 });
      return { workbook, sheet };
    };

    it("brands the header row and sets the print header and footer", async () => {
      const { workbook, sheet } = await build();
      brandWorkbook(workbook, { title: "Budget", project: "Riverside Tower" });

      const header = sheet.getRow(1);
      expect(header.getCell(1).fill.fgColor.argb).toBe(ARGB.midnightIndigo);
      expect(header.getCell(1).font.color.argb).toBe(ARGB.white);
      expect(header.getCell(1).font.bold).toBe(true);

      expect(sheet.headerFooter.oddHeader).toContain("octapm");
      expect(sheet.headerFooter.oddFooter).toContain("Generated by OctaPM");
      expect(sheet.headerFooter.oddFooter).toContain("https://octapm.example.com");
      // The header row repeats on every printed page.
      expect(sheet.pageSetup.printTitlesRow).toBe("1:1");
    });

    it("records who produced the file in the document metadata", async () => {
      const { workbook } = await build();
      brandWorkbook(workbook, { title: "Budget", project: "Riverside Tower" });
      expect(workbook.creator).toBe("OctaPM");
      expect(workbook.company).toBe("OctaPM");
      expect(workbook.description).toContain("Riverside Tower");
    });

    it("does not move any data", async () => {
      const { workbook, sheet } = await build();
      const before = sheet.getRow(2).getCell(1).value;
      brandWorkbook(workbook, { title: "Budget" });
      expect(sheet.getRow(2).getCell(1).value).toBe(before);
      expect(sheet.rowCount).toBe(2);
    });

    it("leaves a data row alone when a sheet has no header", async () => {
      const workbook = new ExcelJS.Workbook();
      const sheet = workbook.addWorksheet("Raw");
      sheet.addRow([1234, 5678]);
      brandWorkbook(workbook, { title: "Raw" });
      expect(sheet.getRow(1).getCell(1).fill).toBeUndefined();
    });

    it("adds an About sheet with a live portal link", async () => {
      const { workbook } = await build();
      addAboutSheet(workbook, { title: "Budget", project: "Riverside Tower" });
      const about = workbook.getWorksheet("About");
      expect(about).toBeDefined();

      const portalRow = about.getRows(1, about.rowCount).find((row) => row.getCell(1).value === "Portal");
      expect(portalRow.getCell(2).value.hyperlink).toBe("https://octapm.example.com");
    });

    it("does not add a second About sheet", async () => {
      const { workbook } = await build();
      workbook.addWorksheet("About");
      addAboutSheet(workbook, { title: "Budget" });
      expect(workbook.worksheets.filter((sheet) => sheet.name === "About")).toHaveLength(1);
    });
  });
});
