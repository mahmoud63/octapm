const { prisma } = require("../config/db");

/**
 * The one way OctaPM issues a human-readable reference.
 *
 * Twenty-two registers used to number themselves `count + 1`. That is only
 * right while nothing has ever been deleted: the seeded project held 53 bid
 * packages numbered up to 73, so the next create asked for 54, which already
 * existed, and died on the unique index with an HTTP 500. One deletion is
 * enough, and it stays broken until enough records climb past the gap
 * (OCTA-API-REFNUM-111).
 *
 * `MAX(existing) + 1` fixes the gap and not the race. Two requests reading the
 * same maximum still compute the same reference, and one of them loses on the
 * unique index — which is the same 500, just rarer and harder to reproduce.
 * So the number does not come from reading at all: it comes from a counter row
 * advanced by a single atomic statement.
 *
 *   INSERT INTO "ReferenceCounter" (scope, next) VALUES (scope, seed)
 *   ON CONFLICT (scope) DO UPDATE SET next = "ReferenceCounter".next + 1
 *   RETURNING next
 *
 * One statement, so it is atomic under any isolation level and works whether
 * or not the caller sits in a transaction — which matters, because these
 * twenty-two call sites are split roughly evenly between the two.
 *
 * The seed is the highest number already issued in that scope, read from the
 * register itself the first time the scope is used. Existing references keep
 * their numbers, and the first new one continues from where the register had
 * got to rather than from 1.
 *
 * Three properties worth stating plainly:
 *
 *   - **Gaps are not filled.** CO-001, CO-002, CO-004 yields CO-005. Filling
 *     CO-003 would mean reusing a reference somebody may already have quoted
 *     in an email; uniqueness beats tidiness.
 *   - **Deleting the newest record does not roll the counter back.** The
 *     counter only ever goes up, so a reference is never handed out twice even
 *     if the row that held it is gone.
 *   - **Hand-written references are ignored.** Only references matching the
 *     generated shape (`PREFIX-` followed by digits) are considered when
 *     seeding, so "VO-SPECIAL" or a reference carried over from a finance
 *     system cannot drag the sequence somewhere strange.
 */

/** Table and column names cannot be bound as parameters, so they are checked. */
const SAFE_IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;
const SAFE_PREFIX = /^[A-Z0-9]+(?:-[A-Z0-9]+)*$/;

const assertIdentifier = (value, what) => {
  if (!SAFE_IDENTIFIER.test(String(value || ""))) {
    throw new Error(`reference-number: unsafe ${what} "${value}"`);
  }
  return value;
};

/**
 * The highest number already issued under this prefix, read from the register.
 * Used once per scope, to seed the counter.
 */
const highestExisting = async (client, { table, column, scopeColumn, scopeId, prefix }) => {
  assertIdentifier(table, "table");
  assertIdentifier(column, "column");
  if (scopeColumn) assertIdentifier(scopeColumn, "scope column");
  if (!SAFE_PREFIX.test(prefix)) {
    throw new Error(`reference-number: unsafe prefix "${prefix}"`);
  }

  // Only rows whose reference was generated by this scheme. A hand-typed
  // reference must not move the sequence.
  const pattern = `^${prefix}-[0-9]+$`;
  const sql =
    `SELECT MAX(SUBSTRING("${column}" FROM ${prefix.length + 2})::int) AS highest ` +
    `FROM "${table}" ` +
    `WHERE "${column}" ~ $1` +
    (scopeColumn ? ` AND "${scopeColumn}" = $2` : "");

  const params = scopeColumn ? [pattern, scopeId] : [pattern];
  const rows = await client.$queryRawUnsafe(sql, ...params);
  return Number(rows?.[0]?.highest) || 0;
};

/**
 * The next reference for a family, as a formatted string.
 *
 * @param {object} client   prisma, or a transaction client — either works
 * @param {object} spec
 * @param {string} spec.table        the register's table, e.g. "ChangeOrder"
 * @param {string} [spec.column]     the reference column, default "ref"
 * @param {string} [spec.scopeColumn] e.g. "projectId" or "orgId"
 * @param {string} [spec.scopeId]    the id it is counted within
 * @param {string} spec.prefix       e.g. "VO"
 * @param {number} [spec.pad]        digits, default 3
 */
const nextReference = async (client, spec) => {
  const { table, column = "ref", scopeColumn = null, scopeId = null, prefix, pad = 3 } = spec;

  const scope = [scopeColumn ? `${scopeColumn}:${scopeId}` : "global", table, prefix].join("|");

  // Seeded from the register the first time this scope is used; afterwards the
  // INSERT loses to the conflict and the counter simply advances.
  const seed = (await highestExisting(client, { table, column, scopeColumn, scopeId, prefix })) + 1;

  const rows = await client.$queryRaw`
    INSERT INTO "ReferenceCounter" ("scope", "next", "updatedAt")
    VALUES (${scope}, ${seed}, NOW())
    ON CONFLICT ("scope") DO UPDATE
      SET "next" = "ReferenceCounter"."next" + 1, "updatedAt" = NOW()
    RETURNING "next"
  `;

  const number = Number(rows?.[0]?.next);
  if (!Number.isFinite(number) || number < 1) {
    throw new Error(`reference-number: counter for ${scope} returned ${rows?.[0]?.next}`);
  }

  return { number, ref: `${prefix}-${String(number).padStart(pad, "0")}` };
};

/** The formatted reference only, for the many callers that want just that. */
const nextRef = async (client, spec) => (await nextReference(client, spec)).ref;

/**
 * The next value for a register that keeps its number in its own integer
 * column and formats the reference separately.
 *
 * Change events, commitments, direct costs, punch items, lookaheads, form
 * instances and sub pay apps all work this way, and all of them read
 * `MAX(number) + 1`. That is gap-safe and race-unsafe: two transactions read
 * the same maximum, both write it, and the second loses on the unique index —
 * the same 500 as `count + 1`, arriving under load instead of after a
 * deletion. READ COMMITTED, which is what these transactions run at, does not
 * prevent it.
 *
 * `scope` may name more than one column, because several of these number
 * separately per type or kind — a subcontract and a purchase order each have
 * their own run of numbers within a project.
 *
 * @param {object} client  prisma, or a transaction client
 * @param {object} spec
 * @param {string} spec.table         e.g. "Commitment"
 * @param {object} spec.scope         equality filters, e.g. { projectId, type }
 * @param {string} [spec.numberColumn] default "number"
 */
const nextNumber = async (client, spec) => {
  const { table, scope = {}, numberColumn = "number" } = spec;
  assertIdentifier(table, "table");
  assertIdentifier(numberColumn, "number column");

  const columns = Object.keys(scope);
  for (const column of columns) assertIdentifier(column, "scope column");

  // Seed from the register's own highest number, so existing runs continue.
  const where = columns.length
    ? " WHERE " + columns.map((c, i) => `"${c}" = $${i + 1}`).join(" AND ")
    : "";
  const seedRows = await client.$queryRawUnsafe(
    `SELECT MAX("${numberColumn}")::int AS highest FROM "${table}"${where}`,
    ...columns.map((c) => scope[c]),
  );
  const seed = (Number(seedRows?.[0]?.highest) || 0) + 1;

  // One counter per distinct scope. Sorted so the key does not depend on the
  // order the caller happened to write the filters in.
  const key = [
    table,
    numberColumn,
    ...columns.sort().map((c) => `${c}:${scope[c]}`),
  ].join("|");

  const rows = await client.$queryRaw`
    INSERT INTO "ReferenceCounter" ("scope", "next", "updatedAt")
    VALUES (${key}, ${seed}, NOW())
    ON CONFLICT ("scope") DO UPDATE
      SET "next" = "ReferenceCounter"."next" + 1, "updatedAt" = NOW()
    RETURNING "next"
  `;

  const number = Number(rows?.[0]?.next);
  if (!Number.isFinite(number) || number < 1) {
    throw new Error(`reference-number: counter for ${key} returned ${rows?.[0]?.next}`);
  }
  return number;
};

/**
 * Drops the counters of a project or an organisation once it is gone.
 *
 * ReferenceCounter sits below tenancy on purpose (schema comment): its rows
 * carry the tenant in the scope key rather than in a column, so no foreign
 * key cascades them away. Both key shapes embed the id — `projectId:<id>|…`
 * / `orgId:<id>|…` for nextReference, and `…|projectId:<id>` /
 * `…|orgId:<id>` for nextNumber — so a purge is a prefix-or-segment match on
 * the scope string (tenant matrix §1.5, ENT-3).
 *
 * For a hard delete only — never an archive. A counter dropped while the
 * register still exists reseeds from the register's highest reference the
 * next time the scope is used, and any reference whose row was deleted before
 * that would be handed out again; the archive keeps its counters for that
 * reason. Today no product path hard deletes a project or an organisation:
 * the callers are the E2E reset and the live kit, which delete throwaway
 * organisations outright and would otherwise leave their counters behind.
 */
const purgeReferenceCounters = async (client, { projectId = null, orgId = null } = {}) => {
  const column = projectId ? "projectId" : orgId ? "orgId" : null;
  const id = projectId || orgId;
  if (!column) throw new Error("reference-number: purge needs a projectId or an orgId");
  const segment = `${column}:${id}`;
  const rows = await client.$queryRaw`
    DELETE FROM "ReferenceCounter"
    WHERE "scope" LIKE ${`${segment}|%`} OR "scope" LIKE ${`%|${segment}`} OR "scope" LIKE ${`%|${segment}|%`}
    RETURNING "scope"
  `;
  return rows.length;
};

module.exports = { nextReference, nextRef, nextNumber, purgeReferenceCounters, prisma };
