/**
 * OctaPM branding for exported spreadsheets.
 *
 * Anything that leaves the portal should be identifiable and should say where
 * it came from. For a workbook that means three things, none of which move a
 * single cell — so parsers, imports and existing tests are unaffected:
 *
 *   1. Document metadata (creator, company, description).
 *   2. A print header and footer, which is what appears when someone actually
 *      prints or exports to PDF: the wordmark and title on top, the signature
 *      and a link to the portal underneath.
 *   3. The sheet's own header row filled in Midnight Indigo with white text,
 *      which is the "header colour" a reader sees on screen.
 *
 * Call `brandWorkbook(workbook, { title })` once, after the sheets are built
 * and before `xlsx.writeBuffer()`.
 */
const { BRAND_NAME, BRAND_TAGLINE, brandUrl } = require("./pdf-writer");

/** ARGB values ExcelJS expects, from the OctaPM palette. */
const ARGB = {
  midnightIndigo: "FF0F1B64",
  royalBlue: "FF325FEC",
  azure: "FF3388FF",
  white: "FFFFFFFF",
  lightGray: "FFF4F6FA",
  border: "FFDFE4EE",
  charcoal: "FF121B21",
};

/**
 * Excel header/footer format codes: &L left, &C centre, &R right, &B bold,
 * &"font" face, &K colour, &P page, &N total pages, &D date.
 */
const printHeader = (title) =>
  `&L&B&"Calibri,Bold"&12&K0F1B64${BRAND_NAME}&C&"Calibri,Regular"&10&K121B21${title || ""}&R&"Calibri,Regular"&9&K5A6672&D`;

const printFooter = () =>
  `&L&"Calibri,Regular"&8&K5A6672Generated by OctaPM  ·  ${BRAND_TAGLINE}` +
  `&C&"Calibri,Regular"&8&K3388FF${brandUrl()}` +
  `&R&"Calibri,Regular"&8&K5A6672Page &P of &N`;

/**
 * True when a row looks like a header: every populated cell is a short string.
 * Guards against filling a data row when a sheet has no header.
 */
const looksLikeHeaderRow = (row) => {
  if (!row || row.cellCount === 0) return false;
  let populated = 0;
  let stringy = 0;
  row.eachCell({ includeEmpty: false }, (cell) => {
    populated += 1;
    const value = cell.value;
    if (typeof value === "string" && value.length > 0 && value.length <= 60) stringy += 1;
  });
  return populated > 0 && stringy === populated;
};

/** Fills one row as a branded table header. */
const brandHeaderRow = (row) => {
  if (!row) return;
  row.eachCell({ includeEmpty: false }, (cell) => {
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: ARGB.midnightIndigo } };
    cell.font = { bold: true, color: { argb: ARGB.white }, size: 10 };
    cell.alignment = { vertical: "middle", wrapText: true, ...(cell.alignment || {}) };
    cell.border = {
      bottom: { style: "thin", color: { argb: ARGB.royalBlue } },
    };
  });
  row.height = Math.max(row.height || 0, 20);
};

/**
 * Applies the brand to a finished workbook.
 *
 * @param {import('exceljs').Workbook} workbook
 * @param {object} options
 * @param {string} options.title      what the document is, for the print header
 * @param {string} [options.project]  project name, added to the metadata
 * @param {boolean} [options.styleHeaderRow=true] fill row 1 of each sheet
 */
function brandWorkbook(workbook, { title = "Export", project = null, styleHeaderRow = true } = {}) {
  if (!workbook) return workbook;

  workbook.creator = "OctaPM";
  workbook.lastModifiedBy = "OctaPM";
  workbook.company = "OctaPM";
  workbook.description = [title, project, BRAND_TAGLINE].filter(Boolean).join(" · ");
  workbook.keywords = "OctaPM, construction, project controls";
  if (!workbook.created) workbook.created = new Date();
  workbook.modified = new Date();

  workbook.eachSheet((sheet) => {
    // What appears on paper, or in an export to PDF.
    sheet.headerFooter = {
      ...(sheet.headerFooter || {}),
      differentFirst: false,
      differentOddEven: false,
      oddHeader: printHeader(title),
      oddFooter: printFooter(),
    };

    // Repeat the header row on every printed page, and fit the width.
    sheet.pageSetup = {
      ...(sheet.pageSetup || {}),
      printTitlesRow: "1:1",
      fitToPage: true,
      fitToWidth: 1,
      fitToHeight: 0,
      margins: {
        left: 0.4, right: 0.4, top: 0.75, bottom: 0.75, header: 0.3, footer: 0.3,
        ...((sheet.pageSetup || {}).margins || {}),
      },
    };

    if (styleHeaderRow) {
      const first = sheet.getRow(1);
      if (looksLikeHeaderRow(first)) brandHeaderRow(first);
    }
  });

  return workbook;
}

/**
 * A closing sheet that states what this file is, when it was produced and
 * where it came from — the spreadsheet equivalent of the PDF's signature.
 * Only added when the workbook has no "About" sheet already.
 */
function addAboutSheet(workbook, { title = "Export", project = null, extra = {} } = {}) {
  if (!workbook || workbook.getWorksheet("About")) return workbook;

  const sheet = workbook.addWorksheet("About");
  sheet.columns = [
    { header: "Field", key: "field", width: 24 },
    { header: "Value", key: "value", width: 62 },
  ];

  const rows = [
    ["Document", title],
    ...(project ? [["Project", project]] : []),
    ["Generated", new Date().toISOString()],
    ["Produced by", `OctaPM — ${BRAND_TAGLINE}`],
    ["Portal", brandUrl()],
    ...Object.entries(extra).map(([key, value]) => [key, value]),
  ];
  rows.forEach(([field, value]) => sheet.addRow({ field, value }));

  brandHeaderRow(sheet.getRow(1));
  sheet.getColumn("field").font = { bold: true, color: { argb: ARGB.charcoal } };
  // The portal link, as a real hyperlink.
  const portalRow = rows.findIndex(([field]) => field === "Portal") + 2;
  const linkCell = sheet.getCell(`B${portalRow}`);
  linkCell.value = { text: brandUrl(), hyperlink: brandUrl() };
  linkCell.font = { color: { argb: ARGB.azure }, underline: true };

  return workbook;
}

module.exports = { ARGB, brandWorkbook, brandHeaderRow, addAboutSheet, printHeader, printFooter };
