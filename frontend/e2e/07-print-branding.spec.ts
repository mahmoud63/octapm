import { expect, test } from '@playwright/test'
import { openProject, SHOTS, signIn } from './support'

/**
 * Printing from the portal.
 *
 * Anything that reaches paper — or a print-to-PDF — should carry the OctaPM
 * band and a signature footer with the portal address, and should drop the
 * navigation chrome. These assert against the print media type rather than
 * the screen.
 */


test.describe('print output', () => {
  test('carries the brand band and signature, and drops the chrome', async ({ page }) => {
    await signIn(page)
    const projectId = await openProject(page)
    await page.goto(`/projects/${projectId}/cost/budget`)
    await page.waitForLoadState('domcontentloaded')
    await page.waitForTimeout(2500)

    await page.emulateMedia({ media: 'print' })

    const printed = await page.evaluate(() => {
      const before = getComputedStyle(document.body, '::before')
      const after = getComputedStyle(document.body, '::after')
      const header = document.querySelector('header')
      const moduleBar = document.querySelector('[data-testid="uat-project-module-bar"]')
      return {
        bandContent: before.content,
        bandBackground: before.backgroundColor,
        bandImage: before.backgroundImage.slice(0, 40),
        footerContent: after.content,
        headerHidden: header ? getComputedStyle(header).display : 'absent',
        moduleBarHidden: moduleBar ? getComputedStyle(moduleBar).display : 'absent',
        printUrl: getComputedStyle(document.documentElement).getPropertyValue('--octa-print-url'),
      }
    })

    // The header band: wordmark on Midnight Indigo, with the octagonal motif.
    expect(printed.bandContent).toContain('octapm')
    expect(printed.bandBackground, 'the print band must be Midnight Indigo').toBe(
      'rgb(15, 27, 100)'
    )
    expect(printed.bandImage, 'the octagonal motif is missing from the band').toContain('url(')

    // The footer signature and the portal address.
    expect(printed.footerContent).toContain('Generated by OctaPM')
    expect(printed.footerContent).toContain('One Platform, Total Project Control')
    expect(printed.printUrl, 'the printed footer should name the running host').toContain(
      'localhost'
    )

    // Navigation is not printed.
    expect(printed.headerHidden).toBe('none')
    expect(printed.moduleBarHidden).toBe('none')

    await page.screenshot({ path: `${SHOTS}/print-01-budget.png`, fullPage: false })
    await page.emulateMedia({ media: 'screen' })
  })

  test('a printed page still shows its data', async ({ page }) => {
    await signIn(page)
    const projectId = await openProject(page)
    await page.goto(`/projects/${projectId}/cost/budget`)
    await page.waitForLoadState('domcontentloaded')
    await page.waitForTimeout(2500)

    // The figure the screen shows is the figure print must keep — whatever the
    // fixture's original budget is (the E2E fixture seeds 1,700,000; a re-run
    // never depends on a number some earlier run left behind).
    const figure = /Original[\s\S]{0,40}?\$([\d,]{5,})/
    await expect(page.locator('body'), 'the original budget is shown on screen').toContainText(figure, { timeout: 30_000 })
    const onScreen = await page.locator('body').innerText()
    const original = figure.exec(onScreen)?.[1]
    expect(original, 'the original budget is shown on screen').toBeTruthy()

    await page.emulateMedia({ media: 'print' })
    const body = await page.locator('body').innerText()

    // Branding must not cost the content: the figures still have to be there.
    expect(body, 'the budget figures vanished when printing').toContain(original as string)
    await page.emulateMedia({ media: 'screen' })
  })

  test('the brand band clears the content on the printed page', async ({ page }) => {
    // The page asks the browser to print as soon as the report mounts, and a
    // real print job stalls the renderer here. Stub it out: this test renders
    // the PDF itself, through page.pdf(), which is the thing being checked.
    await page.addInitScript(() => {
      window.print = () => {}
    })

    await signIn(page)
    const projectId = await openProject(page)
    await page.goto(`/projects/${projectId}/schedule`)
    await page.waitForLoadState('domcontentloaded')
    await page.waitForTimeout(2500)

    // Export → Export PDF mounts the report. window.print() is a no-op in
    // headless Chromium, so the report stays up for page.pdf() to render.
    await page.getByTestId('uat-schedule-export').click()
    await page.getByTestId('uat-schedule-export-pdf').click()
    await expect(page.locator('#print-report')).toBeAttached()

    const pdf = await page.pdf({ printBackground: true, format: 'A4' })
    if (process.env.E2E_DUMP_PDF) {
      const { writeFileSync } = await import('node:fs')
      writeFileSync(process.env.E2E_DUMP_PDF, pdf)
    }

    // Print emulation cannot show this: only a real paginated render places
    // the fixed band against the page box, which is where it used to land on
    // top of the report's title.
    const items = await firstPageText(pdf)
    const band = items.find((item) => item.text.trim() === 'octapm')
    const title = items.find((item) => item.text.includes('Riverside Tower'))

    expect(band, 'the brand band is missing from the printed page').toBeTruthy()
    expect(title, 'the report title is missing from the printed page').toBeTruthy()

    // PDF y grows upward, so the band must sit above the title, with a real
    // gap rather than touching it.
    const gap = band!.y - title!.y
    expect(
      gap,
      `the band overlaps the title (band y=${band!.y.toFixed(1)}, title y=${title!.y.toFixed(1)}, gap ${gap.toFixed(1)}pt)`,
    ).toBeGreaterThan(20)
  })
})

/** Text items on page one of a PDF, with their positions. */
async function firstPageText(buffer: Buffer) {
  const pdfjs = await import(
    /* @vite-ignore */ '../../node_modules/pdfjs-dist/legacy/build/pdf.mjs'
  )
  const doc = await pdfjs.getDocument({ data: new Uint8Array(buffer) }).promise
  const content = await (await doc.getPage(1)).getTextContent()
  return content.items
    .filter((item: unknown): item is { str: string; transform: number[] } =>
      typeof (item as { str?: unknown }).str === 'string',
    )
    .map((item) => ({ text: item.str, y: item.transform[5], x: item.transform[4] }))
}
