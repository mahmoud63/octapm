import { useEffect } from 'react'
import { createPortal } from 'react-dom'
import type { ScheduleActivity } from '../data/schema'

interface Props {
  projectName: string
  projectStartDate?: string | null
  activities: ScheduleActivity[]
}

function toDateLabel(
  projectStartDate: string | null | undefined,
  day: number | null
) {
  if (!projectStartDate || day === null) return '—'
  const d = new Date(projectStartDate)
  d.setDate(d.getDate() + day)
  return d.toLocaleDateString('en-GB')
}

/**
 * The printable schedule report.
 *
 * Rendered through a portal as a direct child of `<body>`, so that printing it
 * is a matter of hiding the application beside it rather than lifting the
 * report out with `position: fixed`. That distinction matters twice over: a
 * fixed block sat on top of the brand band at the top of the page, and it could
 * not flow onto a second sheet — a schedule of any size printed one page and
 * lost the rest.
 */
export function PrintReport({
  projectName,
  projectStartDate,
  activities,
}: Props) {
  const criticalCount = activities.filter((item) => item.isCritical).length
  const avgProgress = activities.length
    ? Math.round(
        activities.reduce(
          (sum, item) => sum + Number(item.pctComplete || 0),
          0
        ) / activities.length
      )
    : 0

  // Marks the document while the report is mounted, so the print rules only
  // hide the application when there is a report to print instead of it.
  useEffect(() => {
    document.body.setAttribute('data-print-mode', 'report')
    return () => document.body.removeAttribute('data-print-mode')
  }, [])

  return createPortal(
    <div id='print-report' className='hidden text-sm print:block'>
      <style>{`
        @media print {
          /* Hide the application, not the report portalled beside it. */
          body[data-print-mode='report'] > *:not(#print-report) { display: none !important; }

          /*
           * The band and the signature are a table header and footer, not fixed
           * elements: a browser repeats thead and tfoot on every printed sheet
           * and reserves the space for them, which is the only way the band both
           * appears on page two and never lands on top of the content. Fixed
           * positioning gave one band, in the wrong place, on the wrong page.
           */
          #print-report .sheet { width: 100%; border-collapse: collapse; }
          #print-report .sheet > thead > tr > td,
          #print-report .sheet > tfoot > tr > td,
          #print-report .sheet > tbody > tr > td { border: 0; padding: 0; }

          #print-report .sheet-band {
            height: 12mm;
            margin-bottom: 6mm;
            padding: 0 6mm;
            display: flex;
            align-items: center;
            font-family: var(--font-display);
            font-weight: 700;
            font-size: 11pt;
            letter-spacing: -0.02em;
            color: #fff;
            background-color: #0f1b64;
            background-image:
              url("data:image/svg+xml;utf8,<svg xmlns='http://www.w3.org/2000/svg' width='72' height='72' viewBox='0 0 72 72'><path d='M22 4h28l18 18v28L50 68H22L4 50V22z' fill='none' stroke='rgba(255,255,255,0.16)' stroke-width='1.5'/></svg>"),
              linear-gradient(100deg, #0a1247 0%, #0f1b64 45%, #1c39a8 82%, #325fec 100%);
            background-size: 22px 22px, 100% 100%;
            background-repeat: repeat-x, no-repeat;
            background-position: right center, center;
            border-bottom: 1.5pt solid #3388ff;
            -webkit-print-color-adjust: exact;
            print-color-adjust: exact;
          }

          #print-report .sheet-signature {
            margin-top: 6mm;
            padding-top: 2mm;
            text-align: center;
            font-size: 7.5pt;
            color: #5a6672;
            border-top: 0.5pt solid #dfe4ee;
          }

          #print-report table.data { border-collapse: collapse; width: 100%; }
          #print-report table.data th, #print-report table.data td { border: 1px solid #d1d5db; padding: 4px 6px; font-size: 10px; }
          #print-report table.data th { background: #0f1b64; color: #fff; -webkit-print-color-adjust: exact; print-color-adjust: exact; }
          #print-report .critical-row td { background: #fdebee; -webkit-print-color-adjust: exact; print-color-adjust: exact; }
          #print-report .page-break { page-break-after: always; }
        }
      `}</style>

      <table className='sheet'>
        <thead>
          <tr>
            <td>
              <div className='sheet-band'>octapm</div>
            </td>
          </tr>
        </thead>
        <tfoot>
          <tr>
            <td>
              <div className='sheet-signature'>
                Generated by OctaPM · One Platform, Total Project Control —{' '}
                {typeof window === 'undefined' ? 'octapm.com' : window.location.host}
              </div>
            </td>
          </tr>
        </tfoot>
        <tbody>
          <tr>
            <td>

      <div className='mb-8 text-center'>
        <h1 className='text-2xl font-bold'>{projectName || 'Project'}</h1>
        <p className='mt-1 text-gray-600'>
          Schedule Report - {new Date().toLocaleDateString('en-GB')}
        </p>
        <div className='mt-4 grid grid-cols-3 gap-4 text-center'>
          <div>
            <p className='text-xl font-bold'>{activities.length}</p>
            <p className='text-xs'>Total Activities</p>
          </div>
          <div>
            <p className='text-xl font-bold text-red-600'>{criticalCount}</p>
            <p className='text-xs'>Critical Activities</p>
          </div>
          <div>
            <p className='text-xl font-bold'>{avgProgress}%</p>
            <p className='text-xs'>Avg Progress</p>
          </div>
        </div>
      </div>

      <div className='page-break' />

      <h2 className='mb-2 text-lg font-bold'>Master Schedule</h2>
      <table className='data'>
        <thead>
          <tr>
            <th>ID</th>
            <th>Activity Name</th>
            <th>Duration</th>
            <th>Early Start</th>
            <th>Early Finish</th>
            <th>TF</th>
            <th>%</th>
            <th>Status</th>
          </tr>
        </thead>
        <tbody>
          {activities.map((item) => (
            <tr key={item.id} className={item.isCritical ? 'critical-row' : ''}>
              <td>{item.wbsCode || item.id.slice(0, 8)}</td>
              <td>{item.name}</td>
              <td>{item.duration}d</td>
              <td>{toDateLabel(projectStartDate, item.earlyStart)}</td>
              <td>{toDateLabel(projectStartDate, item.earlyFinish)}</td>
              <td>{item.totalFloat ?? '—'}</td>
              <td>{item.pctComplete}%</td>
              <td>{item.status.replace('_', ' ')}</td>
            </tr>
          ))}
        </tbody>
      </table>

      <div className='page-break' />

      <h2 className='mb-2 text-lg font-bold'>Critical Path</h2>
      <table className='data'>
        <thead>
          <tr>
            <th>ID</th>
            <th>Activity Name</th>
            <th>Duration</th>
            <th>Early Start</th>
            <th>Early Finish</th>
            <th>%</th>
          </tr>
        </thead>
        <tbody>
          {activities
            .filter((item) => item.isCritical)
            .map((item) => (
              <tr key={item.id}>
                <td>{item.wbsCode || item.id.slice(0, 8)}</td>
                <td>{item.name}</td>
                <td>{item.duration}d</td>
                <td>{toDateLabel(projectStartDate, item.earlyStart)}</td>
                <td>{toDateLabel(projectStartDate, item.earlyFinish)}</td>
                <td>{item.pctComplete}%</td>
              </tr>
            ))}
        </tbody>
      </table>

            </td>
          </tr>
        </tbody>
      </table>
    </div>,
    document.body
  )
}
